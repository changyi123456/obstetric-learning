def h(text, level=2):
    return doc.add_heading(text,level)

def bullets(items):
    for x in items:
        pp = p('• '+x)
        pp.paragraph_format.left_indent = Inches(.1)
        pp.paragraph_format.first_line_indent = Inches(-.1)
        pp.paragraph_format.space_after = Pt(5)

def steps(items):
    for i,x in enumerate(items,1):
        pp=p(f'{i}. {x}')
        pp.paragraph_format.space_after=Pt(5)

def table(headers, rows, widths=None):
    t=doc.add_table(rows=1,cols=len(headers))
    t.alignment=WD_TABLE_ALIGNMENT.CENTER
    t.autofit=False
    if widths is None: widths=[7/len(headers)]*len(headers)
    for i,w in enumerate(widths): t.columns[i].width=Inches(w)
    for i,x in enumerate(headers): t.rows[0].cells[i].text=x
    for row in rows:
        cells=t.add_row().cells
        for i,x in enumerate(row): cells[i].text=str(x)
    pr=t._tbl.tblPr
    borders=OxmlElement('w:tblBorders')
    for edge in ['top','left','bottom','right','insideH','insideV']:
        e=OxmlElement('w:'+edge)
        for k,v in [('val','single'),('sz','5'),('color','D9D9D9')]: e.set(qn('w:'+k),v)
        borders.append(e)
    pr.append(borders)
    for ri,row in enumerate(t.rows):
        trpr=row._tr.get_or_add_trPr()
        if ri==0: trpr.append(OxmlElement('w:tblHeader'))
        trpr.append(OxmlElement('w:cantSplit'))
        for ci,cell in enumerate(row.cells):
            cell.width=Inches(widths[ci])
            cell.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
            cp=cell._tc.get_or_add_tcPr()
            mar=OxmlElement('w:tcMar')
            for edge in ['top','bottom','start','end']:
                el=OxmlElement('w:'+edge);el.set(qn('w:w'),'90');el.set(qn('w:type'),'dxa');mar.append(el)
            cp.append(mar)
            shade=OxmlElement('w:shd');shade.set(qn('w:fill'),'243746' if ri==0 else ('F2F5F7' if ri%2==0 else 'FFFFFF'));cp.append(shade)
            for pp in cell.paragraphs:
                pp.paragraph_format.space_after=Pt(2)
                pp.paragraph_format.line_spacing=Pt(15.5)
                for rr in pp.runs: font(rr,10.2,ri==0,'FFFFFF' if ri==0 else '000000')
    spacer=p()
    spacer.paragraph_format.space_after=Pt(0)
    spacer.paragraph_format.line_spacing=Pt(3)
    return t

